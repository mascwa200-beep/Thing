    -l androidx.room:room-common:2.6.1 \
    -l org.jetbrains.kotlinx:kotlinx-serialization-json-jvm:1.7.3 \
    -l com.squareup.okhttp3:okhttp:4.12.0 \
    $SRC 2>&1 | grep -vE '^curl:')

# ⚠️ Require a success line rather than treating quiet as clean. `android_compile_check.sh` has
# reported "compiles clean" having compiled nothing, and the output of a run that died before reading
# a line is indistinguishable from a pass.
#
# ⚠️ **BOTH phrasings, and the first version of this check accepted only one.** A tree of composables
# cannot reach the backend without the Compose plugin, so the honest answer here is "frontend clean";
# asking only for "compiles clean" reported a clean run as a failure. A gate that cries wolf on a
# passing tree is learnt to be ignored just as fast as one that stays quiet on a broken one.
if echo "$OUT" | grep -qE '^(compiles clean|frontend clean)'; then
    echo "$OUT" | grep -E '^(compiles clean|frontend clean)'
    exit 0
fi
echo "$OUT"
exit 1
